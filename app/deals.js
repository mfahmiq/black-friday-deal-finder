// score: discount weight 0.7 + verdict bonus; drives the default ranking.
export function dealScore(d) {
  const pct = Math.round((1 - d.sale / d.usual) * 100);
  const bonus = { "new-low": 25, strong: 12, good: 5, routine: 0 }[d.verdict] ?? 0;
  return Math.min(100, Math.round(pct * 0.7 + bonus));
}

export function discountPct(d) {
  return Math.round((1 - d.sale / d.usual) * 100);
}

export function money(n) {
  return "$" + n.toFixed(2).replace(/\.00$/, "");
}

